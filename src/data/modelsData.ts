export function getModelById(id: string): StrategicModel | undefined {
  return ALL_MODELS.find(m => m.id === id);
}

export function getModelsByCategory(category: string): StrategicModel[] {
  return ALL_MODELS.filter(m => m.category === category);
}

export function searchModels(query: string): StrategicModel[] {
  const q = query.toLowerCase().trim();
  if (!q) return ALL_MODELS;
  return ALL_MODELS.filter(m =>
    m.name.toLowerCase().includes(q) ||
    m.tagline.toLowerCase().includes(q) ||
    m.strategicQuestion.toLowerCase().includes(q) ||
    m.description.toLowerCase().includes(q) ||
    m.categoryName.toLowerCase().includes(q) ||
    m.whenToUse.some(w => w.toLowerCase().includes(q))
  );
}

